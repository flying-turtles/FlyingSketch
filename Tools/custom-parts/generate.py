"""Generate FlyingSketch's custom parts (fzp + breadboard SVG) under Tools/custom-parts/.

Custom parts are our own work, licensed MIT (Copyright Lars Grof).

Inputs:
  - ESP32 header pin tables: Packages/FlyingSketchKit/Tests/PartsKitTests/Fixtures/esp32*-pins.json
    (name, Espressif "Type" column, function per pin, in physical order; transcribed from the Espressif user guides
    whose URLs are recorded in each file). The catalog tests check the generated parts against the same tables.
  - Board geometry: Espressif dimension drawings (DXF), values below.

Usage: python3 Tools/custom-parts/generate.py   (then re-run catalog-builder, see Tools/README.md)
"""
import json
import os
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "Tools", "custom-parts")
FIXTURES = os.path.join(ROOT, "Packages", "FlyingSketchKit", "Tests", "PartsKitTests", "Fixtures")
NS = "https://github.com/flying-turtles/FlyingSketch"
AUTHOR = "Lars Grof (FlyingSketch)"

# Espressif pin "Type" column -> FlyingSketch PinRole.
ROLE_FOR_TYPE = {"P": "power", "G": "ground", "I/O/T": "digital", "I": "other"}

PITCH = 2.54
# Header columns (DXF drill positions): 1.27 mm from each long edge -> rows 22.86 mm apart.
XL, XR = 1.27, 24.13

BOARDS = [
    dict(
        id="esp32-s3-devkitc-1", title="ESP32-S3-DevKitC-1", fixture="esp32s3-devkitc1-pins.json",
        dxf="https://dl.espressif.com/dl/schematics/esp_idf/DXF_ESP32-S3-DevKitC-1_V1.1_20220429.dxf",
        # PCB 25.4 x 62.87 mm; the ESP32-S3-WROOM-1 module (18 x 25.5 mm) overhangs the PCB by 6.31 mm.
        # SVG (mm, y down) includes the overhang: 25.4 x 69.15. Pin 1 (antenna end) at y 7.85, pin 22 at 61.19.
        w=25.4, h=69.15, pcb_y=6.28, pin1_y=7.85, module=(3.7, 0.0, 18.0, 25.5), module_name="ESP32-S3-WROOM-1",
        usb=[("UART", 4.0), ("USB", 17.6)], buttons=[("BOOT", 7.0), ("RST", 17.5)], button_y=52.0, led="RGB@IO38",
        family="microcontroller board (ESP32-S3)", chip="ESP32-S3"),
    dict(
        id="esp32-c3-devkitm-1", title="ESP32-C3-DevKitM-1", fixture="esp32c3-devkitm1-pins.json",
        dxf="https://dl.espressif.com/dl/schematics/DIMENSION_ESP32-C3-DEVKITM-1_V1_20200915AA.dxf",
        # PCB 25.4 x 38.91 mm; pads at y 1.29 + k * 2.54 from the USB edge -> pin 1 at y 2.06 (antenna end).
        w=25.4, h=38.91, pcb_y=0.0, pin1_y=2.06, module=(6.1, 0.6, 13.2, 16.6), module_name="ESP32-C3-MINI-1",
        usb=[("USB", 12.7)], buttons=[("BOOT", 8.3), ("RST", 17.1)], button_y=27.0, led="RGB@IO8",
        family="microcontroller board (ESP32-C3)", chip="ESP32-C3"),
]


def num(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def fzp(module_id, title, label, description, tags, properties, image, connectors, buses=()):
    """connectors: (id, name, description, svg_id, role or None)."""
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- FlyingSketch custom part (MIT, Lars Grof). Generated by Tools/custom-parts/generate.py. -->",
           f'<module fritzingVersion="0.9.3" moduleId="{escape(module_id)}" xmlns:flyingsketch="{NS}">',
           "  <version>1</version>", f"  <title>{escape(title)}</title>", f"  <label>{label}</label>",
           f"  <author>{AUTHOR}</author>", f"  <description>{escape(description)}</description>", "  <tags>"]
    out += [f"    <tag>{escape(t)}</tag>" for t in tags]
    out += ["  </tags>", "  <properties>"]
    out += [f'    <property name="{escape(k)}">{escape(v)}</property>' for k, v in properties]
    out += ["  </properties>", "  <views>", "    <breadboardView>", f'      <layers image="{image}">',
            '        <layer layerId="breadboard"/>', "      </layers>", "    </breadboardView>", "  </views>", "  <connectors>"]
    for cid, name, desc, svg_id, role in connectors:
        role_attr = f' flyingsketch:role="{role}"' if role else ""
        out += [f'    <connector id="{cid}" name="{escape(name)}" type="male"{role_attr}>',
                f"      <description>{escape(desc)}</description>",
                "      <views>", "        <breadboardView>", f'          <p layer="breadboard" svgId="{svg_id}"/>',
                "        </breadboardView>", "      </views>", "    </connector>"]
    out.append("  </connectors>")
    if buses:
        out.append("  <buses>")
        for i, members in enumerate(buses):
            out.append(f'    <bus id="bus{i}">')
            out += [f'      <nodeMember connectorId="{m}"/>' for m in members]
            out.append("    </bus>")
        out.append("  </buses>")
    out.append("</module>")
    return out


def board(b):
    with open(os.path.join(FIXTURES, b["fixture"])) as fh:
        table = json.load(fh)
    W, H = b["w"], b["h"]
    svg = ['<?xml version="1.0" encoding="UTF-8"?>',
           f'<!-- {b["title"]} {table["revision"]} breadboard view. FlyingSketch custom part (MIT, Lars Grof). -->',
           f'<!-- Geometry: {b["dxf"]} -->',
           f'<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="{num(W)}mm" height="{num(H)}mm" viewBox="0 0 {num(W)} {num(H)}">',
           '<g id="breadboard">',
           f'<rect id="pcb" x="0" y="{num(b["pcb_y"])}" width="{num(W)}" height="{num(H - b["pcb_y"])}" rx="0.5" fill="#1b1b1b" stroke="#000000" stroke-width="0.1"/>']
    mx, my, mw, mh = b["module"]
    zigzag = " ".join(f"{num(mx + 1.5 + i * (mw - 3) / 10)},{num(my + (1.2 if i % 2 == 0 else 5.0))}" for i in range(11))
    svg += [f'<rect id="module" x="{num(mx)}" y="{num(my)}" width="{num(mw)}" height="{num(mh)}" rx="0.3" fill="#20304a"/>',
            f'<rect id="shield" x="{num(mx + 0.8)}" y="{num(my + 6.6)}" width="{num(mw - 1.6)}" height="{num(mh - 7.4)}" rx="0.3" fill="#b8bcc2" stroke="#8a8f96" stroke-width="0.1"/>',
            f'<polyline id="antenna" fill="none" stroke="#c9a227" stroke-width="0.35" points="{zigzag}"/>',
            f'<text x="{num(mx + mw / 2)}" y="{num(my + 6.6 + (mh - 7.4) / 2)}" font-family="Helvetica" font-size="1.3" text-anchor="middle" fill="#30343a">{b["module_name"]}</text>',
            f'<text x="{num(W / 2)}" y="{num(my + mh + 3.0)}" font-family="Helvetica" font-size="1.4" text-anchor="middle" fill="#ffffff">{b["title"]}</text>',
            f'<text x="{num(W / 2)}" y="{num(my + mh + 5.0)}" font-family="Helvetica" font-size="1.0" text-anchor="middle" fill="#bbbbbb">{b["led"]}</text>']
    for name, x in b["buttons"]:
        y = b["button_y"]
        svg += [f'<rect x="{num(x - 2)}" y="{num(y - 1.7)}" width="4" height="3.4" fill="#d0d0d0"/>',
                f'<circle cx="{num(x)}" cy="{num(y)}" r="1.1" fill="#303030"/>',
                f'<text x="{num(x)}" y="{num(y + 3.0)}" font-family="Helvetica" font-size="1.0" text-anchor="middle" fill="#ffffff">{name}</text>']
    for name, x in b["usb"]:
        svg += [f'<rect x="{num(x - 3.9)}" y="{num(H - 5.6)}" width="7.8" height="5.8" fill="#c0c4c8" stroke="#808488" stroke-width="0.1"/>',
                f'<text x="{num(x)}" y="{num(H - 6.2)}" font-family="Helvetica" font-size="1.0" text-anchor="middle" fill="#ffffff">{name}</text>']
    connectors, n = [], 0
    # Pins tied together on the PCB: every ground pin (type G, named G or GND), every 3V3, every 5V -> one bus each.
    rails = {}
    for header, x, anchor, tx in (("J1", XL, "start", XL + 1.3), ("J3", XR, "end", XR - 1.3)):
        for i, pin in enumerate(table["headers"][header]):
            y = b["pin1_y"] + i * PITCH
            svg += [f'<rect id="connector{n}pin" x="{num(x - 0.8)}" y="{num(y - 0.8)}" width="1.6" height="1.6" fill="#c9a227"/>',
                    f'<rect x="{num(x - 0.32)}" y="{num(y - 0.32)}" width="0.64" height="0.64" fill="#3a3a3a"/>',
                    f'<text x="{num(tx)}" y="{num(y + 0.38)}" font-family="Helvetica" font-size="1.05" text-anchor="{anchor}" fill="#ffffff">{escape(pin["name"])}</text>']
            connectors.append((f"connector{n}", pin["name"], f'{header} pin {i + 1}: {pin["function"]}', f"connector{n}pin",
                               ROLE_FOR_TYPE[pin["type"]]))
            rail = "GND" if pin["type"] == "G" else pin["name"] if pin["name"] in ("3V3", "5V") else None
            if rail:
                rails.setdefault(rail, []).append(f"connector{n}")
            n += 1
    svg += ["</g>", "</svg>"]
    d = os.path.join(OUT, b["id"])
    write(os.path.join(d, "breadboard", b["id"] + ".svg"), svg)
    write(os.path.join(d, b["id"] + ".fzp"), fzp(
        f'FlyingSketch-{b["title"]}-{table["revision"]}', b["title"], "U",
        f'Espressif {b["title"]} {table["revision"]} development board ({b["module_name"]}). '
        f'Header pin names and types follow the Espressif user guide: {table["source"]}',
        [b["chip"], "ESP32", "Espressif", "microcontroller"],
        [("family", b["family"]), ("variant", table["revision"]), ("module", b["module_name"])],
        f'breadboard/{b["id"]}.svg', connectors,
        buses=[members for _, members in sorted(rails.items()) if len(members) > 1]))


def pushbutton():
    """6 mm tactile switch, legs exactly 5.08 x 7.62 mm (2 x 3 breadboard pitches) so all four plug in.
    Pin names, ids and buses match Fritzing core pushbutton_4_horizontal.fzp."""
    pid = "pushbutton-6mm"
    W, H = 7.62, 10.16
    # (id, name, x, y, description): left legs x 1.27, right legs x 6.35; top y 1.27, bottom y 8.89.
    legs = [("connector0", "Pin 1", 6.35, 1.27, "pin 1 is always connected with pin 2"),
            ("connector1", "Pin 2", 6.35, 8.89, "pin 2 is always connected with pin 1"),
            ("connector2", "Pin 3", 1.27, 1.27, "pin 3 is always connected with pin 4"),
            ("connector3", "Pin 4", 1.27, 8.89, "pin 4 is always connected with pin 3")]
    svg = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- 6 mm tactile pushbutton breadboard view. FlyingSketch custom part (MIT, Lars Grof). -->",
           f'<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="{num(W)}mm" height="{num(H)}mm" viewBox="0 0 {num(W)} {num(H)}">',
           '<g id="breadboard">']
    for cid, _, x, y, _ in legs:
        svg += [f'<rect x="{num(x - 0.25)}" y="{num(min(y, 5.08))}" width="0.5" height="{num(abs(5.08 - y))}" fill="#9a9a9a"/>',
                f'<rect id="{cid}pin" x="{num(x - 0.5)}" y="{num(y - 0.5)}" width="1" height="1" fill="#8c8c8c"/>']
    svg += ['<rect id="body" x="0.81" y="2.08" width="6" height="6" rx="0.3" fill="#2b2b2b" stroke="#111111" stroke-width="0.1"/>',
            '<circle id="cap" cx="3.81" cy="5.08" r="1.75" fill="#5a5a5a" stroke="#1a1a1a" stroke-width="0.1"/>',
            "</g>", "</svg>"]
    d = os.path.join(OUT, pid)
    write(os.path.join(d, "breadboard", pid + ".svg"), svg)
    write(os.path.join(d, pid + ".fzp"), fzp(
        "FlyingSketch-Pushbutton-6mm", "Pushbutton", "S",
        "6 mm tactile pushbutton, 4 legs on a 5.08 x 7.62 mm (0.2 x 0.3 in) grid.",
        ["Pushbutton", "button", "tactile switch"], [("family", "Switch"), ("package", "[THT]"), ("form", "6 mm tactile")],
        f"breadboard/{pid}.svg", [(cid, name, desc, cid + "pin", None) for cid, name, _, _, desc in legs],
        buses=[("connector0", "connector1"), ("connector2", "connector3")]))


if __name__ == "__main__":
    for b in BOARDS:
        board(b)
    pushbutton()
    print("custom parts written to", OUT)
